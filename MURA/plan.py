_used_anchors = set()


def unique_anchor(base, i):
    if base not in _used_anchors:
        _used_anchors.add(base)
        return base
    for j in range(len(ATTRS)):
        cand = f"{base} — {ATTRS[(i + j) % len(ATTRS)]}"
        if cand not in _used_anchors:
            _used_anchors.add(cand)
            return cand
    raise RuntimeError("anchor space exhausted: " + base)


def cyc(seq):
    return itertools.cycle(seq)

